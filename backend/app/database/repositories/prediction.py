"""Prediction entity repository for Repository Intelligence Platform."""

from __future__ import annotations

from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from backend.app.database.models.prediction import Prediction
from backend.app.database.repositories.base import BaseRepository


class PredictionRepository(BaseRepository[Prediction]):
    """Repository-specific data access for prediction entities."""

    def __init__(self, session: AsyncSession) -> None:
        """Initialize PredictionRepository."""
        super().__init__(session, Prediction)

    async def latest_prediction(
        self,
        repository_snapshot_id: int,
    ) -> Prediction | None:
        """Given a repository snapshot ID, return its newest prediction."""
        stmt = (
            select(Prediction)
            .where(
                Prediction.repository_snapshot_id == repository_snapshot_id,
            )
            .order_by(
                Prediction.prediction_timestamp.desc(),
            )
            .limit(1)
        )
        result = await self.session.execute(stmt)
        return result.scalar_one_or_none()

    async def list_predictions(
        self,
        repository_snapshot_id: int,
    ) -> list[Prediction]:
        """Return every prediction for a snapshot, sorted ascending by prediction timestamp."""
        stmt = (
            select(Prediction)
            .where(
                Prediction.repository_snapshot_id == repository_snapshot_id,
            )
            .order_by(
                Prediction.prediction_timestamp.asc(),
            )
        )
        result = await self.session.execute(stmt)
        return list(result.scalars().all())

    async def latest_by_model(
        self,
        model_version_id: int,
    ) -> Prediction | None:
        """Return the latest single prediction produced by a model version."""
        stmt = (
            select(Prediction)
            .where(
                Prediction.model_version_id == model_version_id,
            )
            .order_by(
                Prediction.prediction_timestamp.desc(),
            )
            .limit(1)
        )
        result = await self.session.execute(stmt)
        return result.scalar_one_or_none()

    async def prediction_history(
        self,
        model_version_id: int,
    ) -> list[Prediction]:
        """Return every prediction generated by one model, ordered newest to oldest."""
        stmt = (
            select(Prediction)
            .where(
                Prediction.model_version_id == model_version_id,
            )
            .order_by(
                Prediction.prediction_timestamp.desc(),
            )
        )
        result = await self.session.execute(stmt)
        return list(result.scalars().all())

    async def high_confidence_predictions(
        self,
        minimum_confidence: float,
    ) -> list[Prediction]:
        """Return predictions meeting or exceeding the specified minimum confidence score."""
        if not (0.0 <= minimum_confidence <= 1.0):
            raise ValueError("minimum_confidence must be between 0.0 and 1.0")

        stmt = (
            select(Prediction)
            .where(
                Prediction.confidence >= minimum_confidence,
            )
            .order_by(
                Prediction.confidence.desc(),
            )
        )
        result = await self.session.execute(stmt)
        return list(result.scalars().all())
